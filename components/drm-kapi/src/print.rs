// Small, source-faithful DRM/LinuxKPI printing surface for the imported DRM
// code. C varargs are not available to Rust macros after translation, so the
// macros below retain each argument as a typed value and interpret the C
// conversion specifiers here. This deliberately does not turn diagnostics into
// no-ops.

