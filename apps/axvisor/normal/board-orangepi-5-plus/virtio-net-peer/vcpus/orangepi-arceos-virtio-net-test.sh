#!/usr/bin/env bash
# Generate the fixed 64-peer configuration and run the standard board case.
set -euo pipefail
case_dir=$(cd "$(dirname "$0")" && pwd)
workspace=$(cd "$case_dir/../../../../../.." && pwd)
cd "$workspace"
mode=${1:-run}
if (($#)); then shift; fi
count=64
output="$workspace/target/axvisor-arceos-net-scale"
server=${BOARD_SERVER:-}
usage() {
    echo "Usage: $0 [gen|run] [--server URL]"
}
while (($#)); do
    case "$1" in
    --server)
        (($# >= 2)) || { usage >&2; exit 2; }
        server=$2
        shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
    esac
done
case "$mode" in gen|run) ;; -h|--help) usage; exit 0 ;; *) usage >&2; exit 2 ;; esac

gen_configs() {
    # The runner builds this shared guest before packaging the host initramfs.
    mkdir -p "$output"
    local n cpu cpu_id cpu_mask image_path
    image_path=$(python3 -c 'import json, sys; print(json.dumps(sys.argv[1]))' \
        "${AXBUILD_TARGET_DIR:-$workspace/target}/aarch64-unknown-linux-musl/release/arceos-virtio-net-peer.bin")
    for ((n=1; n<=count; n++)); do
        cpu=$(((n - 1) % 8))
        cpu_id=$((cpu * 256))
        cpu_mask=$((1 << cpu))
        cat > "$output/vm$n.toml" <<EOF_VM
# Generated by orangepi-arceos-virtio-net-test.sh; do not edit.
[base]
id = $n
name = "arceos-net-vm$n"
guest_type = "virtualized"
cpu_num = 1
phys_cpu_ids = [$cpu_id]
phys_cpu_sets = [$cpu_mask]

[kernel]
entry_point = 0x80200000
kernel_load_addr = 0x80200000
kernel_path = $image_path
dtb_load_addr = 0x80000000
memory_regions = [[0x80000000, 67108864, 7, 0]]

[devices]
passthrough = []
disabled = [
  { path = "/pcie@fe150000" },
  { path = "/pcie@fe160000" },
  { path = "/pcie@fe170000" },
  { path = "/pcie@fe180000" },
  { path = "/pcie@fe190000" },
]

[[devices.virtual]]
id = "console0"
model = "uart16550-mmio"
address = 0xfeb50000

[[devices.virtual]]
id = "virtnet0"
model = "virtio-net"
guest_mac = [82, 84, 0, 32, 1, $n]
EOF_VM
    done
    printf 'Generated %s ArceOS peers, 64 MiB each: %s\n' "$count" "$output"
}

run_board() {
    [[ -n "$server" ]] || { echo "Set BOARD_SERVER or pass --server URL" >&2; return 2; }
    mkdir -p "$output"
    local status=0
    cargo xtask axvisor app board -t board-orangepi-5-plus/virtio-net-peer/vcpus \
        -b BallPick-Robot-Rk3588 --server "$server" 2>&1 | tee "$output/board.log" || status=$?
    printf '{"passed":%s,"cargo_exit":%s,"count":%s,"linux_observers":1,"same_boot":true}\n' \
        "$([[ "$status" == 0 ]] && echo true || echo false)" "$status" "$count" > "$output/result.json"
    return "$status"
}

case "$mode" in
gen) gen_configs ;;
run) run_board ;;
esac
