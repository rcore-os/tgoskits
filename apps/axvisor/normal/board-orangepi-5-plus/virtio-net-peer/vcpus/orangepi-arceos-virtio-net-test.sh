#!/usr/bin/env bash
# Prepare and run the ArceOS peers using the native cargo xtask entry.
set -euo pipefail
case_dir=$(cd "$(dirname "$0")" && pwd)
workspace=$(cd "$case_dir/../../../../../.." && pwd)
cd "$workspace"
mode=run
if (($#)); then mode=$1; shift; fi
count=64
memory_mib=64
tgosimages="$HOME/tgosimages"
output="$workspace/target/axvisor-arceos-net-scale"
images_dir=
server=http://10.3.10.60:2999
with_removal=0
usage() {
    echo "Usage: $0 [gen|build-images|build|run] [--count N] [--memory-mib N]"
    echo "       [--tgosimages DIR] [--images-dir DIR] [--output DIR]"
    echo "       [--server URL] [--with-removal]"
}
while (($#)); do
    case "$1" in
    --with-removal) with_removal=1; shift ;;
    --count|--memory-mib|--tgosimages|--images-dir|--output|--server)
        (($# >= 2)) || { usage >&2; exit 2; }
        case "$1" in
        --count) count=$2 ;; --memory-mib) memory_mib=$2 ;;
        --tgosimages) tgosimages=$2 ;; --images-dir) images_dir=$2 ;;
        --output) output=$2 ;; --server) server=$2 ;;
        esac
        shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
    esac
done
case "$mode" in gen|build-images|build|run) ;; -h|--help) usage; exit 0 ;; *) usage >&2; exit 2 ;; esac
[[ "$count" =~ ^[1-9][0-9]{0,2}$ && "$memory_mib" =~ ^[1-9][0-9]{0,3}$ ]] || { echo "Invalid count or memory" >&2; exit 2; }
((count >= 2 && count <= 240 && memory_mib >= 32 && count * memory_mib + 1024 <= 6144)) || { echo "Require 2..240 guests, >=32 MiB each, <=6144 MiB including the 1 GiB Linux observer" >&2; exit 2; }
tgosimages=$(realpath -m "$tgosimages")
if [[ -z "$images_dir" ]]; then images_dir="$tgosimages/IMAGES/orangepi/arceos"; fi
images_dir=$(realpath -m "$images_dir")
output=$(realpath -m "$output")
if [[ "$mode" == run ]]; then with_removal=1; fi

build_images() {
    mkdir -p "$images_dir"
    bash "$tgosimages/build.sh" platform orangepi-5-plus arceos \
        --src-dir "$workspace" --images-dir "$images_dir"
    python3 - "$workspace" "$case_dir" "$images_dir" <<'PY_MANIFEST'
import hashlib
import json
from pathlib import Path
import subprocess
import sys
repo, app, images = map(Path, sys.argv[1:])
config = app.parent / "arceos-guest-build.toml"
image = images / "orangepi-5-plus"
(images / "manifest.json").write_text(json.dumps({
    "source_commit": subprocess.check_output(
        ["git", "-C", str(repo), "rev-parse", "HEAD"], text=True).strip(),
    "source_dirty": bool(subprocess.check_output(
        ["git", "-C", str(repo), "status", "--porcelain"], text=True)),
    "guest_source_sha256": hashlib.sha256(
        (repo / "apps/arceos/virtio-net-peer/src/main.rs").read_bytes()).hexdigest(),
    "build_config_sha256": hashlib.sha256(config.read_bytes()).hexdigest(),
    "identity": "MAC 52:54:00:20:01:N -> VMN, 10.0.2.(14+N)",
    "image": image.name,
    "sha256": hashlib.sha256(image.read_bytes()).hexdigest(),
}, indent=2) + "\n")
PY_MANIFEST
}

# TOML basic strings need escaping for paths supplied by the caller.
toml_string() {
    local value=$1
    value=${value//\\/\\\\}
    value=${value//\"/\\\"}
    value=${value//$'\n'/\\n}
    value=${value//$'\r'/\\r}
    value=${value//$'\t'/\\t}
    printf '"%s"' "$value"
}

management() {
    printf '\n[[shell_check_steps]]\nshell_prefix = "axvisor:/$"\nshell_cmd = "%s"\n' "$1"
    printf "success_regex = ['%s']\ntimeout = 180\n" "$2"
}

gen_configs() {
    [[ -s "$images_dir/orangepi-5-plus" ]] || { echo "Run build-images first" >&2; exit 1; }
    mkdir -p "$output"
    local n cpu cpu_id cpu_mask memory_bytes image_path selector= marker success
    memory_bytes=$((memory_mib * 1024 * 1024))
    image_path=$(toml_string "$images_dir/orangepi-5-plus")
    for ((n=1; n<=count; n++)); do
        cpu=$(((n - 1) % 8))
        cpu_id=$((cpu * 256))
        cpu_mask=$((1 << cpu))
        cat > "$output/vm$n.toml" <<EOF_VM
# Generated by orangepi-arceos-virtio-net-test.sh; do not edit.
[base]
id = $n
name = "arceos-net-vm$n"
guest_type = "virtualized"
cpu_num = 1
phys_cpu_ids = [$cpu_id]
phys_cpu_sets = [$cpu_mask]

[kernel]
entry_point = 0x80200000
kernel_load_addr = 0x80200000
kernel_path = $image_path
dtb_load_addr = 0x80000000
memory_regions = [[0x80000000, $memory_bytes, 7, 0]]

[devices]
passthrough = []
disabled = [
  { path = "/pcie@fe150000" },
  { path = "/pcie@fe160000" },
  { path = "/pcie@fe170000" },
  { path = "/pcie@fe180000" },
  { path = "/pcie@fe190000" },
]

[[devices.virtual]]
id = "console0"
model = "uart16550-mmio"
address = 0xfeb50000

[[devices.virtual]]
id = "virtnet0"
model = "virtio-net"
guest_mac = [82, 84, 0, 32, 1, $n]
EOF_VM
        if [[ -n "$selector" ]]; then selector+=,; fi
        selector+=$n
    done
    # Keep the observer ID adjacent to the selected ArceOS range.
    observer_id=$((count + 1))
    sed "s/^id = 65$/id = $observer_id/" "$case_dir/../linux-observer.toml" > "$output/linux-observer.toml"
    selector+=",$observer_id"
    # The checked-in config owns the host parameters; generated files vary only the VM list.
    sed '/^vm_configs[[:space:]]*=/,$d' "$case_dir/build-aarch64-unknown-none-softfloat.toml" > "$output/build.toml"
    {
        echo 'vm_configs = ['
        printf '  '; toml_string "$output/linux-observer.toml"; printf ',\n'

        for ((n=1; n<=count; n++)); do
            printf '  '; toml_string "$output/vm$n.toml"; printf ',\n'
        done
        echo ']'
    } >> "$output/build.toml"
    # The standard 64-peer run uses the checked-in board case.
    if ((count == 64 && with_removal)); then
        cp "$case_dir/smoke/board-orangepi-5-plus-arceos-net.toml" "$output/board.toml"
        printf 'Generated %s ArceOS peers, %s MiB each, %s MiB plus 1024 MiB Linux: %s\n' "$count" "$memory_mib" "$((count * memory_mib))" "$output"
        return
    fi
    {
        echo 'board_type = "BallPick-Robot-Rk3588"'
        echo 'timeout = 3600'
        printf 'cmdline = "root=/dev/mmcblk0p2 rw console=ttyS2,1500000 earlycon=uart8250,mmio32,0xfeb50000 rootwait rootfstype=ext4 axvisor.vm_start=%s"\n' "$selector"
        echo "fail_regex = ['(?i)\bpanic(?:ked)?\b', 'failed to initialize default VMs', '(?m)^SCALE_[A-Z_]*FAILED\r?$', 'Failed to stop VM', 'Failed to remove VM', 'VM[0-9]*_VIRTIO_NET_FAIL']"
        for ((n=1; n<=count; n++)); do
            if ((n == 1)); then
                marker=VM1_VIRTIO_NET_HB_TX
                success="$marker.*ack=\"ACK VM2 seq="
            else
                marker="VM${n}_VIRTIO_NET_HB_RX"
                success="$marker.*payload=\"HB VM$((n - 1)) seq="
            fi
            printf '\n[[shell_check_steps]]\nshell_prefix = "axvisor:/$"\nshell_cmd = "vm console %s"\n' "$n"
            printf "success_regex = ['%s']\ntimeout = 300\n" "$success"
            printf '\n[[shell_check_steps]]\nshell_prefix = "%s"\nshell_cmd = "\\u0018h"\ntimeout = 120\n' "$marker"
        done
        observer_attach
        observer_check before "$count"
        observer_detach
        if ((with_removal)); then
            for ((n=1; n<count; n++)); do
                management "vm stop $n" "VM\[$n\] stopped successfully"
                management "vm delete $n" "VM\[$n\] removed from VM list"
            done
            observer_attach
            observer_check partial "$count"
            observer_detach
            management "vm stop $count" "VM\[$count\] stopped successfully"
            management "vm delete $count" "VM\[$count\] removed from VM list"
            observer_attach
            observer_check after "$count"
            observer_detach
            management "vm stop $observer_id" "VM\[$observer_id\] stopped successfully"
            management "vm delete $observer_id" "VM\[$observer_id\] removed from VM list"
            management 'vm list' 'No virtual machines found\.'
        fi
    } > "$output/board.toml"
    printf 'Generated %s ArceOS peers, %s MiB each, %s MiB plus 1024 MiB Linux: %s\n' "$count" "$memory_mib" "$((count * memory_mib))" "$output"
}

observer_attach() {
    management "vm console $observer_id\n:" "Attached VM\[$observer_id\] console"
}

observer_detach() {
    printf '\n[[shell_check_steps]]\nshell_prefix = "root@linux-observer:~#"\nshell_cmd = "\\u0018h"\ntimeout = 120\n'
}

observer_check() {
    local phase=$1
    printf '\n[[shell_check_steps]]\nshell_prefix = "root@linux-observer:~#"\nshell_cmd = '
    echo "'''"
    cat <<EOF_CHECK
{
if sh -s -- $phase $count <<'LINUX_CHECK'
set -eu
phase=\$1
count=\$2
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
mkdir -p /proc /sys /dev
mount -t proc proc /proc 2>/dev/null || grep -q ' /proc proc ' /proc/mounts
test -d /sys/class/net || mount -t sysfs sysfs /sys
ip link set lo up
ip link set eth0 up
ip addr replace 10.0.2.2/24 dev eth0
command -v ping >/dev/null
test "\$(cat /sys/class/net/eth0/carrier)" = 1
n=1
while [ "\$n" -le "\$count" ]; do
    ip="10.0.2.\$((14 + n))"
    expected=down
    if [ "\$phase" = before ] || { [ "\$phase" = partial ] && [ "\$n" -eq "\$count" ]; }; then
        expected=up
    fi
    if ping -n -c 2 -W 1 "\$ip" >/dev/null 2>&1; then rc=0; else rc=\$?; fi
    if [ "\$expected" = up ]; then
        [ "\$rc" -eq 0 ]
        mac=\$(printf '52:54:00:20:01:%02x' "\$n")
        ip neigh show "\$ip" dev eth0 | grep -qi "lladdr \$mac "
    else
        # iputils exit 1 means no replies; exit 2 is an execution/network error.
        [ "\$rc" -eq 1 ]
    fi
    printf 'SCALE_TARGET phase=%s vm=%s ip=%s expected=%s ping_exit=%s\n' "\$phase" "\$n" "\$ip" "\$expected" "\$rc"
    n=\$((n + 1))
done
test "\$(cat /sys/class/net/eth0/carrier)" = 1
sync
LINUX_CHECK
then
    printf '\nSCALE_%s_PASS\n' \$(printf %s $phase | tr a-z A-Z)
else
    printf '\nSCALE_%s_FAILED\n' \$(printf %s $phase | tr a-z A-Z)
fi
}
EOF_CHECK
    echo "'''"
    printf "success_regex = ['(?m)^SCALE_%s_PASS[[:space:]]*$']\ntimeout = 600\n" "$(printf %s "$phase" | tr a-z A-Z)"
}

run_board() {
    local status=0
    if ((count == 64)) && [[ "$output" == "$workspace/target/axvisor-arceos-net-scale" ]]; then
        cargo xtask axvisor test board -g normal --board orangepi-5-plus-arceos-net -c smoke \
            -b BallPick-Robot-Rk3588 --server "$server" 2>&1 | tee "$output/board.log" || status=$?
    else
        cargo xtask axvisor board --config "$output/build.toml" \
            --board-config "$output/board.toml" -b BallPick-Robot-Rk3588 \
            --server "$server" 2>&1 | tee "$output/board.log" || status=$?
    fi
    printf '{"passed":%s,"cargo_exit":%s,"count":%s,"linux_observers":1,"same_boot":true}\n' \
        "$([[ "$status" == 0 ]] && echo true || echo false)" "$status" "$count" > "$output/result.json"
    return "$status"
}

case "$mode" in
gen) gen_configs ;;
build-images) build_images ;;
build) build_images; gen_configs; cargo xtask axvisor build -c "$output/build.toml" ;;
run) gen_configs; run_board ;;
esac
